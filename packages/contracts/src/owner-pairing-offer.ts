import { z } from "zod";

/**
 * Owner pairing offer (private owner-loopback contract, version 1): the human owner of THIS base creates a one-time
 * invitation for a paired Apple app (iPhone or Mac) from the app itself, without the `dexter app-client offer` CLI.
 *
 * - Human owner loopback only (`createHostApp`). Never the paired-client router, an engine/harness tool, MCP or
 *   `exportContracts()` (this file is deliberately absent from the public contract catalog).
 * - Reuses the running host's app-client channel: its TLS identity, listener and `ClientPairingRegistry`. Nothing here
 *   generates a certificate, a key or a Keychain item; without a validated listening channel the action is unavailable.
 * - Every mutation carries the host it was decided on, the journal revision AND journal pin it saw (`journalPin`: canonical
 *   authority generation + journal instance; a restore/activation or a lost journal changes it) and one client request
 *   UUID; an old request without a receipt is refused under another pin, never re-executed. The
 *   journal reserves the revision and the request before the registry effect; an exact replay returns the original
 *   receipt, the same id with another body conflicts, and a lost ACK is read back with GET (never re-posted automatically).
 * - Scopes are closed and explicit: the eight historical scopes are named one by one and `outputs.read` /
 *   `outputs.manage` are separate opt-ins (manage never includes read). There is no default list and no rotation here.
 * - The invitation text carries the one-time code. It is never persisted (receipts keep only its SHA-256 pin), never in
 *   events, logs, tool catalogs, checkpoints or mutation metadata; the host retains it in memory for a finite number of
 *   deliveries until the offer expires, is claimed or cancelled. After a restart it is gone: the receipt still proves the
 *   offer exists, and the owner cancels it and/or creates a new one. A code is never re-issued for the same request.
 */
export const OWNER_PAIRING_OFFER_CONTRACT_VERSION = 1 as const;
export const OWNER_PAIRING_OFFER_LIMITS = Object.freeze({
  /** Lower bound for an offer the owner chooses; the upper bound is the host's configured app-client offer TTL (<= 1 h). */
  minTtlSeconds: 60, maxTtlSeconds: 3600,
  /** Deliveries of one invitation text (the POST response counts as one). */
  invitationDeliveries: 3,
  invitationBytes: 8192,
});
/** The scopes every app-client offer carried before output folders, listed one by one on purpose (never "all cases"). */
export const OWNER_PAIRING_HISTORICAL_SCOPES = Object.freeze(["approvals.decide", "approvals.read", "chat.read", "chat.write",
  "devices.manage", "devices.read", "grants.manage", "grants.read"] as const);
/** Output-folder scopes: only when the owner turns each one on. `outputs.manage` does not include `outputs.read`. */
export const OWNER_PAIRING_OPT_IN_SCOPES = Object.freeze(["connections.manage", "connections.read", "mcp.manage", "mcp.read", "outputs.manage", "outputs.read"] as const);
export const OwnerPairingScopeSchema = z.enum([...OWNER_PAIRING_HISTORICAL_SCOPES, ...OWNER_PAIRING_OPT_IN_SCOPES]);
export type OwnerPairingScope = z.infer<typeof OwnerPairingScopeSchema>;
export const OwnerPairingRoleSchema = z.enum(["client-ios", "client-mac"]);
export type OwnerPairingRole = z.infer<typeof OwnerPairingRoleSchema>;

const HostId = z.string().min(1).max(128);
const Hash = z.string().regex(/^[0-9a-f]{64}$/);
const Timestamp = z.number().int().min(0).max(Number.MAX_SAFE_INTEGER);
const Revision = z.number().int().min(1).max(Number.MAX_SAFE_INTEGER);
/** Canonical lowercase UUID generated by the owner app for ONE decision; every retry of that decision reuses it. */
export const OwnerPairingRequestIdSchema = z.string().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
export const OwnerPairingOfferIdSchema = z.string().regex(/^cof_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
/** Closed, unique and sorted (the registry and the invitation importer require sorted scopes). 0..10. */
export const OwnerPairingScopesSchema = z.array(OwnerPairingScopeSchema).max(14)
  .refine(value => new Set(value).size === value.length && value.every((scope, i) => i === 0 || value[i - 1]! < scope), "Scopes must be unique and sorted.");

export const OwnerPairingUnavailableReasonSchema = z.enum([
  "app_client_channel_unconfigured", "app_client_listener_not_listening", "app_client_certificate_not_valid", "app_client_offer_ttl_too_short",
  "host_closing",
]);
export type OwnerPairingUnavailableReason = z.infer<typeof OwnerPairingUnavailableReasonSchema>;
/** Real channel facts, read live: the HTTPS listener, its pinned certificate and the installation offers belong to. */
export const OwnerPairingChannelSchema = z.strictObject({
  status: z.enum(["listening", "not_listening", "unconfigured"]),
  installationId: HostId.nullable(),
  hostUrl: z.string().min(1).max(512).nullable(),
  hostFingerprint: Hash.nullable(),
  certificateNotAfter: Timestamp.nullable(),
});
export const OwnerPairingStatusSchema = z.strictObject({
  version: z.literal(OWNER_PAIRING_OFFER_CONTRACT_VERSION),
  hostId: HostId,
  /** Journal revision every mutation must name (1 before the first decision). */
  revision: Revision,
  /**
   * Pin of this journal's continuity (authority epoch + journal instance), present while offers can be created. Every
   * mutation must name it: after a checkpoint restore/activation or a lost journal it changes, so a request formed before
   * cannot be accepted as new (an existing receipt is still replayed).
   */
  journalPin: Hash.nullable(),
  availability: z.enum(["available", "unavailable"]),
  reason: OwnerPairingUnavailableReasonSchema.nullable(),
  channel: OwnerPairingChannelSchema,
  /** Null while the channel is unconfigured. `maxSeconds` is the host's configured offer TTL. */
  ttl: z.strictObject({ minSeconds: z.number().int().min(1).max(3600), maxSeconds: z.number().int().min(1).max(3600),
    defaultSeconds: z.number().int().min(1).max(3600) }).nullable(),
  roles: z.array(OwnerPairingRoleSchema),
  scopes: z.strictObject({ historical: z.array(OwnerPairingScopeSchema), optIn: z.array(OwnerPairingScopeSchema) }),
  limits: z.strictObject({ invitationDeliveries: z.number().int().min(1), invitationBytes: z.number().int().min(1) }),
});
export type OwnerPairingStatus = z.infer<typeof OwnerPairingStatusSchema>;

/** POST /v1/owner/app-client-pairing/offers. Exactly these keys; no owner, grant, capability or kind field exists. */
export const CreateOwnerPairingOfferSchema = z.strictObject({
  expectedHostId: HostId,
  expectedRevision: Revision,
  expectedJournalPin: Hash,
  clientRequestId: OwnerPairingRequestIdSchema,
  role: OwnerPairingRoleSchema,
  scopes: OwnerPairingScopesSchema,
  ttlSeconds: z.number().int().min(OWNER_PAIRING_OFFER_LIMITS.minTtlSeconds).max(OWNER_PAIRING_OFFER_LIMITS.maxTtlSeconds),
});
export type CreateOwnerPairingOffer = z.infer<typeof CreateOwnerPairingOfferSchema>;
/** POST /v1/owner/app-client-pairing/offers/:offerId/cancel. Only offers created through this journal. */
export const CancelOwnerPairingOfferSchema = z.strictObject({
  expectedHostId: HostId,
  expectedRevision: Revision,
  expectedJournalPin: Hash,
  clientRequestId: OwnerPairingRequestIdSchema,
});
export type CancelOwnerPairingOffer = z.infer<typeof CancelOwnerPairingOfferSchema>;

export const OwnerPairingOfferSchema = z.strictObject({
  offerId: OwnerPairingOfferIdSchema,
  kind: z.literal("pair"),
  role: OwnerPairingRoleSchema,
  scopes: OwnerPairingScopesSchema,
  expiresAt: Timestamp,
  installationId: HostId,
  hostUrl: z.string().min(1).max(512),
  hostFingerprint: Hash,
});
/**
 * Durable receipt (no code). `unknown`: the reservation committed but the registry outcome was not confirmed; the offer, if
 * any, can never be shown (its code was never delivered) and expires by itself. `grantsCreated` is always 0.
 */
export const OwnerPairingReceiptSchema = z.strictObject({
  version: z.literal(OWNER_PAIRING_OFFER_CONTRACT_VERSION),
  hostId: HostId,
  clientRequestId: OwnerPairingRequestIdSchema,
  requestHash: Hash,
  operation: z.enum(["create", "cancel"]),
  previousRevision: Revision,
  revision: Revision,
  outcome: z.enum(["created", "cancelled", "unknown"]),
  offer: OwnerPairingOfferSchema.nullable(),
  /** SHA-256 of the exact invitation text (create only): pins every later delivery to this receipt. */
  invitationSha256: Hash.nullable(),
  grantsCreated: z.literal(0),
  createdAt: Timestamp,
});
export type OwnerPairingReceipt = z.infer<typeof OwnerPairingReceiptSchema>;
/** Live facts read now: the registry state of the offer and whether this host still retains its invitation in memory. */
export const OwnerPairingLiveSchema = z.strictObject({
  offerState: z.enum(["open", "claimed", "cancelled", "exhausted", "expired", "unknown"]),
  invitation: z.enum(["retained", "not_retained"]),
});
export const OwnerPairingRecordSchema = z.strictObject({ receipt: OwnerPairingReceiptSchema, live: OwnerPairingLiveSchema });
export type OwnerPairingRecord = z.infer<typeof OwnerPairingRecordSchema>;
/** The private invitation text the other device pastes: exactly the `dexter app-client offer` bundle JSON plus "\n". */
export const OwnerPairingInvitationSchema = z.strictObject({
  text: z.string().min(2).max(OWNER_PAIRING_OFFER_LIMITS.invitationBytes),
  sha256: Hash,
  deliveriesRemaining: z.number().int().min(0).max(OWNER_PAIRING_OFFER_LIMITS.invitationDeliveries),
});
export const OwnerPairingOfferResultSchema = z.strictObject({ record: OwnerPairingRecordSchema, invitation: OwnerPairingInvitationSchema.nullable() });
export type OwnerPairingOfferResult = z.infer<typeof OwnerPairingOfferResultSchema>;
export const OwnerPairingInvitationUnavailableReasonSchema = z.enum(["expired", "claimed", "cancelled", "exhausted", "not_retained", "delivery_limit", "outcome_unknown"]);
/** GET .../receipts/:clientRequestId/invitation?requestHash=<receipt.requestHash>. */
export const OwnerPairingInvitationReadSchema = z.discriminatedUnion("availability", [
  z.strictObject({ version: z.literal(OWNER_PAIRING_OFFER_CONTRACT_VERSION), hostId: HostId, clientRequestId: OwnerPairingRequestIdSchema,
    offerId: OwnerPairingOfferIdSchema, availability: z.literal("available"), invitation: OwnerPairingInvitationSchema }),
  z.strictObject({ version: z.literal(OWNER_PAIRING_OFFER_CONTRACT_VERSION), hostId: HostId, clientRequestId: OwnerPairingRequestIdSchema,
    offerId: OwnerPairingOfferIdSchema.nullable(), availability: z.literal("unavailable"), reason: OwnerPairingInvitationUnavailableReasonSchema }),
]);
export type OwnerPairingInvitationRead = z.infer<typeof OwnerPairingInvitationReadSchema>;
