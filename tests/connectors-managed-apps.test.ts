    const began = new Promise<void>(r => { entered = r; }), pending = hold<ManagedAccountReceipt>();
    s.onLookup(async (r) => { req = r; calls++; entered(); return calls === 1 ? pending.promise : { ...s.receipt(r), accountId: "ca_other" }; });
    const first = s.service.reconcile("op1"), second = s.service.reconcile("op1");
