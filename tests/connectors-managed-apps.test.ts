import { ManagedAppsService, type ManagedAppsProvider, type ManagedAccountReceipt, type ManagedProvisionRequest } from "@dexter/connectors";
const HOST = "backend.composio.dev", SECRET = "synthetic-project-secret-never-persist", VERSION = "20260901_00";
const TOOL: ToolManifest = { name: "slack.read", toolkit: "slack", upstreamSlug: "SLACK_READ_MESSAGES", version: VERSION, description: "Synthetic read", upstreamHost: HOST, effect: "read", destinationArgument: "channel", destinationOrigins: null, inputSchema: { type: "object", additionalProperties: false, required: ["channel"], properties: { channel: { type: "string", maxLength: 32, enum: ["C-approved"] } } } };
const fails = (code: string) => (e: unknown) => !!e && typeof e === "object" && "code" in e && e.code === code;
const hold = <T>() => { let resolve!: (value: T) => void; const promise = new Promise<T>(r => { resolve = r; }); return { promise, resolve }; };
function setup(t: TestContext) {
    const dir = mkdtempSync(join(tmpdir(), "dexter-managed-apps-")), store = new HostStore({ dataDir: dir });
    const gateway = new CapabilityGateway({ store, broker: { acquire: () => null, secretValues: () => [SECRET, 'synthetic"quoted\\secret'] }, adapter: { execute: async () => ({ synthetic: true }) } });
    const bot = store.createBot({ name: "Synthetic", profileId: "work", engine: "claude" });
    let catalog: readonly ToolManifest[] = [TOOL], effects = 0, lookups = 0;
    let provisionHook: ((req: ManagedProvisionRequest) => Promise<ManagedAccountReceipt>) | null = null;
    let catalogHook: (() => Promise<readonly ToolManifest[]>) | null = null;
    let accountHook: ((receipt: ManagedAccountReceipt, signal: AbortSignal) => Promise<ManagedAccountReceipt>) | null = null;
    let lookupReceipt: ManagedAccountReceipt | null = null;
    let lookupHook: ((req: ManagedProvisionRequest) => Promise<ManagedAccountReceipt | null>) | null = null;
    const receipt = (req: ManagedProvisionRequest): ManagedAccountReceipt => ({ installationId: req.installationId, ownerId: req.ownerId, profileId: req.profileId, toolkit: req.toolkit, userId: req.userId, accountId: "ca_synthetic", version: req.version, status: "active" });
    const provider: ManagedAppsProvider = { catalog: async () => catalogHook ? catalogHook() : catalog, provision: async (req) => { effects++; lookupReceipt = receipt(req); return provisionHook ? provisionHook(req) : receipt(req); }, lookup: async (req) => { lookups++; return lookupHook ? lookupHook(req) : lookupReceipt; }, account: async (r, signal) => accountHook ? accountHook(r, signal) : r };
    const services: ManagedAppsService[] = [];
    const open = () => { const s = new ManagedAppsService({ store, gateway, provider, credentialRef: "cred-composio", upstreamHost: HOST, secretValues: () => [SECRET, 'synthetic"quoted\\secret'] }); services.push(s); return s; };
    t.after(async () => {
        for (const s of services)
            await s.close().catch(() => undefined);
        gateway.close();
        store.close();
        rmSync(dir, { recursive: true, force: true });
    });
    const service = open(), input = { profileId: "work", toolkit: "slack", version: VERSION, label: "Work" };
    const ready = async () => { const rev = await service.syncCatalog(0); service.approveTools(rev, [TOOL.name]); };
    const cap = () => { const thread = store.createThread(bot.id), turn = store.createTurn(thread.id, { clientRequestId: "synthetic", content: "synthetic" }).turn; store.claimNextTurn(thread.id); return gateway.issueCapability({ turnId: turn.id }).token; };
    return { dir, store, gateway, bot, service, open, input, ready, cap, receipt, counts: () => ({ effects, lookups }), setCatalog: (v: readonly ToolManifest[]) => { catalog = v; }, onCatalog: (fn: () => Promise<readonly ToolManifest[]>) => { catalogHook = fn; }, onProvision: (fn: (r: ManagedProvisionRequest) => Promise<ManagedAccountReceipt>) => { provisionHook = fn; }, onAccount: (fn: (r: ManagedAccountReceipt, signal: AbortSignal) => Promise<ManagedAccountReceipt>) => { accountHook = fn; }, onLookup: (fn: (req: ManagedProvisionRequest) => Promise<ManagedAccountReceipt | null>) => { lookupHook = fn; }, setLookup: (r: ManagedAccountReceipt | null) => { lookupReceipt = r; } };
}
test("catalog requires explicit review; account confirmation grants nothing; capabilities stay per running turn", async (t) => {
    const s = setup(t);
    await s.service.syncCatalog(0);
    assert.throws(() => s.service.provision("op1", s.input), fails("forbidden"));
    s.service.approveTools(1, [TOOL.name]);
    const op = await s.service.provision("op1", s.input);
    assert.equal(op.state, "confirmed");
    const token = s.cap();
    assert.deepEqual(s.gateway.listTools(token), []);
    s.service.grant({ operationId: "op1", botId: s.bot.id, tool: TOOL.name, policy: "ask" });
    assert.equal(s.gateway.listTools(token)[0]?.requiresApproval, true);
    const binding = s.service.find({ installationId: s.store.hostId, ownerId: s.store.ownerId, profileId: "work", botId: s.bot.id, threadId: "synthetic", turnId: "synthetic" }, op.connectionId!);
    assert.equal(binding?.connectedAccountId, "ca_synthetic");
    assert.deepEqual(binding?.tools, [{ slug: TOOL.upstreamSlug, version: VERSION }]);
    assert.equal(s.service.find({ installationId: s.store.hostId, ownerId: "other", profileId: "work", botId: s.bot.id, threadId: "synthetic", turnId: "synthetic" }, op.connectionId!), null);
});
